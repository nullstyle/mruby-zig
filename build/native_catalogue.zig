pub fn findSource(path: []const u8) ?Source {
    for (sources) |source| if (std.mem.eql(u8, source.path, path)) return source;
    return null;
}
pub fn allowed(name: []const u8) ?bool {
    for (natives) |entry| if (std.mem.eql(u8, entry.name, name)) return entry.allowed;
    return null;
}
