//! C-code generators replicating the file templates of the upstream Rake
//! build: `tasks/mrblib.rake`, `lib/mruby/gem.rb#generate_gem_init`, and
//! `tasks/mrbgems.rake`. Output text matches Rake where it matters
//! (function names, call order); comment banners are equivalent.

const std = @import("std");
const Gem = @import("gems.zig").Gem;

const Emitter = struct {
    buf: std.Io.Writer.Allocating,

    fn init(a: std.mem.Allocator) Emitter {
        return .{ .buf = .init(a) };
    }

    fn print(self: *Emitter, comptime fmt: []const u8, args: anytype) !void {
        try self.buf.writer.print(fmt, args);
    }

    fn raw(self: *Emitter, s: []const u8) !void {
        try self.buf.writer.writeAll(s);
    }

    fn slice(self: *Emitter) []const u8 {
        return self.buf.writer.buffer[0..self.buf.writer.end];
    }
};

const gem_banner =
    \\/*
    \\ * This file is loading the irep
    \\ * Ruby GEM code.
    \\ *
    \\ * IMPORTANT:
    \\ *   This file was generated!
    \\ *   All manual changes will get lost.
    \\ */
    \\
;

/// Footer of `build/<target>/mrblib/mrblib.c` (after the `mrbc -S -s` body).
pub fn mrblibFooter(a: std.mem.Allocator) ![]const u8 {
    var e = Emitter.init(a);
    try e.raw(
        \\
        \\void
        \\mrb_init_mrblib(mrb_state *mrb)
        \\{
        \\  mrblib_proc_init_syms(mrb);
        \\  mrb_load_proc(mrb, mrblib_proc);
        \\}
        \\
    );
    return e.slice();
}

/// Header of a gem's `gem_init.c` (before the `mrbc -S -s` body, if any).
/// Mirrors `print_gem_init_header`: gems with Ruby files need only stdlib.h
/// because the cdump body brings its own includes.
pub fn gemInitHeader(a: std.mem.Allocator, gem: Gem) ![]const u8 {
    var e = Emitter.init(a);
    try e.raw(gem_banner);
    if (gem.rb_files.len != 0) {
        try e.raw("#include <stdlib.h>\n");
    } else {
        try e.raw("#include <mruby.h>\n");
    }
    return e.slice();
}

/// Footer of a gem's `gem_init.c`: declarations + GENERATED_TMP wrappers.
pub fn gemInitFooter(a: std.mem.Allocator, gem: Gem) ![]const u8 {
    const fn_ = gem.funcname(try a.alloc(u8, gem.name.len));
    const has_c = gem.c_srcs.len != 0;
    const has_rb = gem.rb_files.len != 0;

    var e = Emitter.init(a);
    if (has_c) {
        try e.print("void mrb_{s}_gem_init(mrb_state *mrb);\n", .{fn_});
        try e.print("void mrb_{s}_gem_final(mrb_state *mrb);\n", .{fn_});
        try e.raw("\n");
    }
    try e.print("void GENERATED_TMP_mrb_{s}_gem_init(mrb_state *mrb) {{\n", .{fn_});
    if (has_rb) try e.print("  gem_mrblib_{s}_proc_init_syms(mrb);\n", .{fn_});
    if (has_c) try e.print("  mrb_{s}_gem_init(mrb);\n", .{fn_});
    if (has_rb) try e.print("  mrb_load_proc(mrb, gem_mrblib_{s}_proc);\n", .{fn_});
    try e.raw("}\n\n");
    try e.print("void GENERATED_TMP_mrb_{s}_gem_final(mrb_state *mrb) {{\n", .{fn_});
    if (has_c) try e.print("  mrb_{s}_gem_final(mrb);\n", .{fn_});
    try e.raw("}\n");
    return e.slice();
}

/// The top-level `build/<target>/mrbgems/gem_init.c` (tasks/mrbgems.rake).
pub fn topGemInit(a: std.mem.Allocator, gems: []const Gem) ![]const u8 {
    var e = Emitter.init(a);
    try e.raw(
        \\/*
        \\ * This file contains a list of all
        \\ * initializing methods which are
        \\ * necessary to bootstrap all gems.
        \\ *
        \\ * This file was generated by mruby-zig.
        \\ *
        \\ * IMPORTANT:
        \\ *   This file was generated!
        \\ *   All manual changes will get lost.
        \\ */
        \\
        \\
        \\#include <mruby.h>
        \\#include <mruby/error.h>
        \\#include <mruby/proc.h>
        \\
        \\
    );
    if (gems.len == 0) {
        try e.raw(
            \\void
            \\mrb_init_mrbgems(mrb_state *mrb) {
            \\}
            \\
        );
        return e.slice();
    }
    for (gems) |gem| {
        const fn_ = gem.funcname(try a.alloc(u8, gem.name.len));
        try e.print("void GENERATED_TMP_mrb_{s}_gem_init(mrb_state*);\n", .{fn_});
        try e.print("void GENERATED_TMP_mrb_{s}_gem_final(mrb_state*);\n", .{fn_});
    }
    try e.raw(
        \\
        \\static const struct {
        \\  void (*init)(mrb_state*);
        \\  void (*final)(mrb_state*);
        \\} gem_funcs[] = {
        \\
    );
    for (gems) |gem| {
        const fn_ = gem.funcname(try a.alloc(u8, gem.name.len));
        try e.print("  {{ GENERATED_TMP_mrb_{s}_gem_init, GENERATED_TMP_mrb_{s}_gem_final }},\n", .{ fn_, fn_ });
    }
    try e.raw(
        \\};
        \\
        \\
        \\#define NUM_GEMS ((int)(sizeof(gem_funcs) / sizeof(gem_funcs[0])))
        \\
        \\struct final_mrbgems {
        \\  int i;
        \\  int ai;
        \\};
        \\
        \\static mrb_value
        \\final_mrbgems_body(mrb_state *mrb, void *ud) {
        \\  struct final_mrbgems *p = (struct final_mrbgems*)ud;
        \\  for (; p->i >= 0; p->i--) {
        \\    gem_funcs[p->i].final(mrb);
        \\    mrb_gc_arena_restore(mrb, p->ai);
        \\  }
        \\  return mrb_nil_value();
        \\}
        \\
        \\static void
        \\mrb_final_mrbgems(mrb_state *mrb) {
        \\  struct final_mrbgems a = { NUM_GEMS - 1, mrb_gc_arena_save(mrb) };
        \\  for (; a.i >= 0; a.i--) {
        \\    mrb_protect_error(mrb, final_mrbgems_body, &a, NULL);
        \\    mrb_gc_arena_restore(mrb, a.ai);
        \\  }
        \\}
        \\
        \\
        \\void
        \\mrb_init_mrbgems(mrb_state *mrb) {
        \\  int ai = mrb_gc_arena_save(mrb);
        \\  for (int i = 0; i < NUM_GEMS; i++) {
        \\    gem_funcs[i].init(mrb);
        \\    mrb_gc_arena_restore(mrb, ai);
        \\    mrb_vm_ci_env_clear(mrb, mrb->c->cibase);
        \\    if (mrb->exc) {
        \\      mrb_exc_raise(mrb, mrb_obj_value(mrb->exc));
        \\    }
        \\  }
        \\  mrb_state_atexit(mrb, mrb_final_mrbgems);
        \\}
        \\
    );
    return e.slice();
}
